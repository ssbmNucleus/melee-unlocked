#!/usr/bin/env python3
# The id of the layouts a fighter plugin is compiled against, as a C header.
# SPDX-License-Identifier: GPL-2.0-or-later
"""usage: mexft_abi.py --out mexft_abi.h FILE_OR_DIR...

A fighter plugin (sourceport/game/mexft/mexft_plugin.h) works with a game library when both were
compiled with the same struct layouts and the same adapter: the MexTK headers the fighter's C
includes, mexft/mex.h, the adapter and the descriptor's header. The id is the first 16 bytes of
the SHA-256 of those files (each a path relative to its argument, then its contents with line
ends as LF, so a checkout's line ends do not change it), in path order. The game library has the
id it was built with, and a plugin carries the one it was built with."""
import argparse
import hashlib
import os


def files(root):
    if os.path.isfile(root):
        yield os.path.basename(root), root
        return
    for folder, _dirs, names in os.walk(root):
        for name in names:
            if name.endswith(('.h', '.inc')):
                path = os.path.join(folder, name)
                yield os.path.relpath(path, root).replace(os.sep, '/'), path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('inputs', nargs='+')
    a = ap.parse_args()
    h = hashlib.sha256()
    count = 0
    for root in a.inputs:
        for rel, path in sorted(files(root)):
            h.update(rel.encode() + b'\0')
            h.update(open(path, 'rb').read().replace(b'\r\n', b'\n') + b'\0')
            count += 1
    abi = h.digest()[:16]
    text = ('/* Generated by tools/mexft/mexft_abi.py from %d files: do not edit. */\n'
            '#define MEXFT_ABI_BYTES %s\n#define MEXFT_ABI_TEXT "%s"\n' % (
                count, ', '.join('0x%02X' % b for b in abi), abi.hex()))
    old = open(a.out).read() if os.path.exists(a.out) else None
    if old != text:
        os.makedirs(os.path.dirname(a.out) or '.', exist_ok=True)
        open(a.out, 'w', newline='\n').write(text)
    print('mexft abi %s (%d files)' % (abi.hex(), count))


if __name__ == '__main__':
    main()

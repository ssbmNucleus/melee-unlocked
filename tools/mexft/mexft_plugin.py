#!/usr/bin/env python3
# Makes a fighter plugin from one m-ex fighter's prepared objects.
# SPDX-License-Identifier: GPL-2.0-or-later
"""A fighter plugin (sourceport/game/mexft/mexft_plugin.h) is the fighter's code as a file of its
own, which the game links when it loads it (mexft_plugins.c) instead of having it linked in.

The file is one relocatable object: the fighter's modules after tools/tmce/link_module.py (MexTK
names already renamed to the decomp's), the object of its generated descriptor (mexft_<name>.c),
and a record made here that lists the fighters and carries the id of the layouts all of it was
compiled against (tools/mexft/mexft_abi.py). Every name stays private except the record's, and
the references to the game stay undefined: the game fills them in by name.

usage: mexft_plugin.py --gcc GCC --ld LD --objcopy OBJCOPY --nm NM --header-dir DIR --abi-dir DIR
                       --name NAME --fighter SYMBOL[=M-EX NAME] [--fighter ...]
                       [--game-syms melee_game.syms] --out FILE.mufighter OBJ...

--fighter: a descriptor's symbol (mu_ak_mexft_<name>) and, after "=", the name MxDt gives the
fighter: the game then finds the fighter by that name in whatever slot a build gave it.
--game-syms: check now that the game library of that file has every symbol the plugin uses (the
game checks again when it loads the plugin).
"""
import argparse
import os
import struct
import subprocess
import sys


def build_id(dll):
    """The 16 bytes after "RSDS" in the CodeView record of a PE file's debug directory."""
    data = open(dll, 'rb').read()
    pe = struct.unpack_from('<I', data, 0x3C)[0]
    if data[pe:pe + 4] != b'PE\0\0':
        sys.exit('%s: not a PE file' % dll)
    sections = struct.unpack_from('<H', data, pe + 6)[0]
    optional = pe + 24
    optional_size = struct.unpack_from('<H', data, pe + 20)[0]
    if struct.unpack_from('<H', data, optional)[0] != 0x20B:
        sys.exit('%s: not a 64-bit PE file' % dll)
    rva, size = struct.unpack_from('<II', data, optional + 112 + 6 * 8)
    table = optional + optional_size

    def offset(r):
        for i in range(sections):
            vsize, vaddr, rsize, raw = struct.unpack_from('<IIII', data, table + i * 40 + 8)
            if vaddr <= r < vaddr + max(vsize, rsize):
                return raw + r - vaddr
        return None

    at = offset(rva) if rva else None
    for i in range(size // 28 if at is not None else 0):
        kind, length, _rva, raw = struct.unpack_from('<IIII', data, at + i * 28 + 12)
        if kind == 2 and length >= 20 and data[raw:raw + 4] == b'RSDS':
            return data[raw + 4:raw + 20]
    sys.exit('%s: no build id (the game library is linked with --build-id)' % dll)


def c_string(text):
    return '"%s"' % text.replace('\\', '\\\\').replace('"', '\\"')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--gcc', required=True)
    ap.add_argument('--ld', required=True)
    ap.add_argument('--objcopy', required=True)
    ap.add_argument('--nm', required=True)
    ap.add_argument('--header-dir', required=True, help='the folder of mexft_plugin.h')
    ap.add_argument('--abi-dir', required=True, help='the folder of the generated mexft_abi.h')
    ap.add_argument('--name', required=True)
    ap.add_argument('--fighter', action='append', required=True)
    ap.add_argument('--game-syms')
    ap.add_argument('--out', required=True)
    ap.add_argument('objs', nargs='+')
    a = ap.parse_args()

    work = a.out + '.work'
    os.makedirs(work, exist_ok=True)
    fighters = [(f.split('=', 1) + [None])[:2] for f in a.fighter]

    record_c = os.path.join(work, 'plugin.c')
    record_o = os.path.join(work, 'plugin.o')
    with open(record_c, 'w', newline='\n') as f:
        f.write('/* Generated by tools/mexft/mexft_plugin.py: do not edit. */\n')
        f.write('#include "mexft_plugin.h"\n#include "mexft_abi.h"\n\n')
        for symbol, _name in fighters:
            f.write('extern const char %s[];\n' % symbol)
        f.write('\nstatic const MuFighterPluginEntry fighters[] = {\n')
        for symbol, name in fighters:
            f.write('    { %s, %s },\n' % (symbol, c_string(name) if name else '0'))
        f.write('};\n\nconst MuFighterPlugin mu_fighter_plugin = {\n')
        f.write('    MU_FIGHTER_PLUGIN_MAGIC, MU_FIGHTER_PLUGIN_VERSION, { MEXFT_ABI_BYTES }, fighters, %d,\n};\n'
                % len(fighters))
    subprocess.run([a.gcc, '-O2', '-g0', '-I', a.header_dir, '-I', a.abi_dir, '-c', record_c, '-o', record_o],
                   check=True)

    joined = os.path.join(work, 'joined.o')
    subprocess.run([a.ld, '-r', '-o', joined] + a.objs + [record_o], check=True)
    # Private names, no debug information, no symbols the loader has no use for.
    subprocess.run([a.objcopy, '--strip-debug', '--strip-unneeded', '--keep-global-symbol=mu_fighter_plugin',
                    joined, a.out], check=True)

    undefined = set()
    for line in subprocess.run([a.nm, a.out], capture_output=True, text=True, check=True).stdout.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == 'U':
            undefined.add(parts[1])
    if a.game_syms:
        game = set(line.split()[0] for line in open(a.game_syms) if line.strip() and not line.startswith('#'))
        missing = sorted(undefined - game)
        if missing:
            os.remove(a.out)
            sys.exit('mexft plugin %s: the game library has no symbol %s' % (a.name, ', '.join(missing)))
    print('mexft plugin %s: %d fighters, %d game symbols, %d bytes -> %s' % (
        a.name, len(fighters), len(undefined), os.path.getsize(a.out), a.out))


if __name__ == '__main__':
    main()

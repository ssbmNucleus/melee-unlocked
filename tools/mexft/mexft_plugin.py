#!/usr/bin/env python3
# Links one m-ex fighter's prepared objects into a fighter plugin for one build of the game library.
# SPDX-License-Identifier: GPL-2.0-or-later
"""A fighter plugin (sourceport/game/mexft/mexft_plugin.h) is the fighter's code as a file of its
own, which the game loads at startup (mexft_plugins.c) instead of having it linked in.

It is linked for ONE build of the game library and imports nothing: each game symbol its objects
use is given the address that symbol has in that build (--game-syms, "name address" lines made
with nm from the library's debug file), as an assignment in a linker script. The game library's
build id (the CodeView record its linker wrote, --game-dll) goes into the plugin, and the game
loads only a plugin that names its own.

The inputs are what the in-tree build already makes for a fighter: its modules after
tools/tmce/link_module.py (MexTK names already renamed to the decomp's) and the object of its
generated descriptor (mexft_<name>.c).

usage: mexft_plugin.py --gcc GCC --nm NM --game-syms FILE --game-dll FILE --header-dir DIR
                       --name NAME --base 0x84000000 --fighter SYMBOL [--fighter SYMBOL ...]
                       --out FILE.mufighter OBJ...
"""
import argparse
import os
import struct
import subprocess
import sys

# Symbols the linker itself defines for the plugin's own image: never the game's.
OWN = ('__CTOR_LIST__', '__DTOR_LIST__', '__data_start__', '__data_end__', '__bss_start__', '__bss_end__',
       '__ImageBase', '__image_base__')


def build_id(dll):
    """The 16 bytes after "RSDS" in the CodeView record of a PE file's debug directory."""
    data = open(dll, 'rb').read()
    pe = struct.unpack_from('<I', data, 0x3C)[0]
    if data[pe:pe + 4] != b'PE\0\0':
        sys.exit('%s: not a PE file' % dll)
    sections = struct.unpack_from('<H', data, pe + 6)[0]
    optional = pe + 24
    optional_size = struct.unpack_from('<H', data, pe + 20)[0]
    if struct.unpack_from('<H', data, optional)[0] != 0x20B:
        sys.exit('%s: not a 64-bit PE file' % dll)
    rva, size = struct.unpack_from('<II', data, optional + 112 + 6 * 8)
    table = optional + optional_size

    def offset(r):
        for i in range(sections):
            vsize, vaddr, rsize, raw = struct.unpack_from('<IIII', data, table + i * 40 + 8)
            if vaddr <= r < vaddr + max(vsize, rsize):
                return raw + r - vaddr
        return None

    at = offset(rva) if rva else None
    for i in range(size // 28 if at is not None else 0):
        kind, length, _rva, raw = struct.unpack_from('<IIII', data, at + i * 28 + 12)
        if kind == 2 and length >= 20 and data[raw:raw + 4] == b'RSDS':
            return data[raw + 4:raw + 20]
    sys.exit('%s: no build id (the game library is linked with --build-id)' % dll)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--gcc', required=True)
    ap.add_argument('--nm', required=True)
    ap.add_argument('--game-syms', required=True)
    ap.add_argument('--game-dll', required=True)
    ap.add_argument('--header-dir', required=True, help='the folder of mexft_plugin.h')
    ap.add_argument('--name', required=True)
    ap.add_argument('--base', required=True)
    ap.add_argument('--fighter', action='append', required=True, help="a descriptor's symbol (mu_ak_mexft_<name>)")
    ap.add_argument('--out', required=True)
    ap.add_argument('objs', nargs='+')
    a = ap.parse_args()

    base = int(a.base, 0)
    work = a.out + '.work'
    os.makedirs(work, exist_ok=True)
    game_id = build_id(a.game_dll)

    stub_c = os.path.join(work, 'plugin.c')
    stub_o = os.path.join(work, 'plugin.o')
    with open(stub_c, 'w', newline='\n') as f:
        f.write('/* Generated by tools/mexft/mexft_plugin.py: do not edit. */\n')
        f.write('#include "mexft_plugin.h"\n\n')
        for s in a.fighter:
            f.write('extern const char %s[];\n' % s)
        f.write('extern char __data_start__[], __data_end__[], __bss_start__[], __bss_end__[];\n')
        f.write('typedef void (*Constructor)(void);\n')
        f.write('extern Constructor __CTOR_LIST__[];\n\n')
        f.write('/* The linker\'s list: a count word (or -1), the constructors, 0. */\n')
        f.write('static void init(void)\n{\n    int i;\n')
        f.write('    for (i = 1; __CTOR_LIST__[i] != 0; i++) {\n        __CTOR_LIST__[i]();\n    }\n}\n\n')
        f.write('static const void* const fighters[] = { %s };\n\n' % ', '.join(a.fighter))
        f.write('__declspec(dllexport) const MuFighterPlugin mu_fighter_plugin = {\n')
        f.write('    MU_FIGHTER_PLUGIN_MAGIC, MU_FIGHTER_PLUGIN_VERSION,\n')
        f.write('    { %s },\n' % ', '.join('0x%02X' % b for b in game_id))
        f.write('    0x%Xull, init, fighters, %d,\n' % (base, len(a.fighter)))
        f.write('    __data_start__, __data_end__, __bss_start__, __bss_end__,\n};\n')
    subprocess.run([a.gcc, '-O2', '-g0', '-I', a.header_dir, '-c', stub_c, '-o', stub_o], check=True)

    objs = a.objs + [stub_o]
    undefined, defined = set(), set()
    for line in subprocess.run([a.nm] + objs, capture_output=True, text=True, check=True).stdout.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == 'U':
            undefined.add(parts[1])
        elif len(parts) == 3 and parts[1].isupper():
            defined.add(parts[2])
    game = {}
    for line in open(a.game_syms):
        parts = line.split()
        if len(parts) == 2:
            game[parts[0]] = parts[1]
    need = sorted(undefined - defined - set(OWN))
    missing = [s for s in need if s not in game]
    if missing:
        sys.exit('mexft plugin %s: this game build has no symbol %s' % (a.name, ', '.join(missing)))
    script = os.path.join(work, 'game.ld')
    with open(script, 'w', newline='\n') as f:
        f.write('/* The game library\'s addresses for build %s. */\n' % game_id.hex())
        for s in need:
            f.write('%s = 0x%s;\n' % (s, game[s]))

    # No entry point, no C runtime, no relocations: the file is the fighter's code and data at
    # `base`, and the one export.
    subprocess.run([a.gcc, '-shared', '-nostdlib', '-s', '-o', a.out] + objs + [script,
                   '-Wl,--image-base,0x%X' % base, '-Wl,--disable-dynamicbase', '-Wl,--disable-high-entropy-va',
                   '-Wl,--disable-reloc-section', '-Wl,-e,0', '-Wl,--disable-runtime-pseudo-reloc'], check=True)
    print('mexft plugin %s: %d game symbols, base %08X, game build %s -> %s' % (
        a.name, len(need), base, game_id.hex(), a.out))


if __name__ == '__main__':
    main()

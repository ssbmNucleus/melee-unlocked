def load_tool(rel):
    spec = importlib.util.spec_from_file_location('tool_' + Path(rel).stem, TOOLS / rel)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def decodes(data: bytes) -> bool:
    try:
        data.decode('utf-8')
        return True
    except UnicodeDecodeError:
        return False


def run_guard_asm(work, target, log):
    """tools/guard_asm.py on every file the ported tree guards (its own selection was by hand)."""
    tool = load_tool('guard_asm.py')
    files = sorted(p for p, d in target.items() if b'#ifndef MU_NATIVE /* PowerPC assembly */' in d and p in work.files)
    for p in files:
        names = tool.guard(work.dir / p)
        log.append('%s: %d guarded' % (p, len(names)))
    return files, 'python tools/guard_asm.py ' + ' '.join(files)


def run_gxpipe(work, target, log):
    tool = load_tool('gxpipe_rewrite.py')

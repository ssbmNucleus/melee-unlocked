# ---- "of this rewriter's kind": the by-hand differences ----

WS = re.compile(r'\s+')


def strip_wrappers(text, names):
    for name in names:
        pat = re.compile(r'(?<![\w])' + name + r'\s*\(')
        while True:
            m = pat.search(text)
            if not m:
                break
            depth, k = 0, m.end() - 1
            while k < len(text):
                depth += {'(': 1, ')': -1}.get(text[k], 0)
                if depth == 0:
                    break
                k += 1
            text = text[:m.start()] + text[m.end():k] + text[k + 1:]
    return text


GUARD_LINE = re.compile(r'(?m)^[ \t]*(#ifndef MU_NATIVE /\* PowerPC assembly \*/|#endif)[ \t]*$')
GX_STORE = re.compile(r'\bGXWGFifo\.(u8|u16|u32|u64|s8|s16|s32|s64|f32|f64)\s*=\s*(.+?);')
GX_PASTE = re.compile(r'\bGXWGFifo\.T\s*=\s*(\w+);')
BE_NAMES = {'be_f32': 'f32', 'be_u32': 'u32', 'be_s32': 's32', 'be_u16': 'u16', 'be_s16': 's16',
            'Vec3_BE': 'Vec3', 'Vec2_BE': 'Vec2', 'Quaternion_BE': 'Quaternion', 'Mtx_BE': 'Mtx'}


def undo_disc_ptr(text):
    while True:
        m = re.search(r'DISC_PTR\s*\(', text)
        if not m:
            return text
        depth, k = 0, m.end() - 1
        while k < len(text):
            depth += {'(': 1, ')': -1}.get(text[k], 0)
            if depth == 0:
                break
            k += 1
        text = text[:m.start()] + text[m.end():k] + '*' + text[k + 1:]


class Kind:
    """What one rewriter changes: a normalizer that undoes it, and the tokens that show it."""

    def __init__(self, name, tokens, norm, accept=None):
        self.name, self.tokens, self._norm, self.accept = name, tokens, norm, accept

    def norm(self, text):
        return WS.sub('', self._norm(text))

    def shows(self, text):
        return any(t in text for t in self.tokens)


KIND_GUARD = Kind('guard_asm', ('MU_NATIVE /* PowerPC assembly */',), lambda t: GUARD_LINE.sub('', t))
KIND_GX = Kind('gxpipe_rewrite', ('GXW_', 'GXWGFifo'),
               lambda t: GX_PASTE.sub(lambda m: 'GXW_##T(%s);' % m[1], GX_STORE.sub(lambda m: 'GXW_%s(%s);' % (m[1], m[2]), t)))
KIND_CONVERT = Kind('disc_convert', ('DISC_STRUCT', 'DISC_PTR', '_BE', 'be_'),
                    lambda t: re.sub(r'\b(' + '|'.join(BE_NAMES) + r')\b', lambda m: BE_NAMES[m[1]],
                                     undo_disc_ptr(re.sub(r'\bDISC_STRUCT\b', '', t))))
KIND_DP = Kind('disc_wrap', ('DP(',), lambda t: strip_wrappers(t, ['DP']))
KIND_UNWRAP = Kind('disc_unwrap', ('DP(',), lambda t: strip_wrappers(t, ['DP']),
                   accept=lambda a, b: a.count('DP(') > b.count('DP('))
KIND_WRAP_MORE = Kind('disc_wrap', ('DP(',), lambda t: strip_wrappers(t, ['DP']),
                      accept=lambda a, b: a.count('DP(') <= b.count('DP('))
KIND_Z = Kind('cast_census', ('MU_Z(',), lambda t: strip_wrappers(t, ['MU_Z']))
KIND_P = Kind('MU_P', ('MU_P(',), lambda t: strip_wrappers(t, ['MU_P']))
KIND_TAG = Kind('tag_no_contract', ('MU_NO_CONTRACT',), lambda t: re.sub(r'\bMU_NO_CONTRACT\b\s*', '', t))
ALL_KINDS = [KIND_GUARD, KIND_GX, KIND_CONVERT, KIND_DP, KIND_Z, KIND_P, KIND_TAG]
KIND_ANY = Kind('mechanical', tuple(t for k in ALL_KINDS for t in k.tokens),
                lambda t: KIND_TAG._norm(strip_wrappers(KIND_CONVERT._norm(KIND_GX._norm(KIND_GUARD._norm(t))),
                                                        ['DP', 'MU_Z', 'MU_P'])))


def take_kind(cur: str, tgt: str, kind: Kind) -> str:
    """cur with every difference from tgt that is only `kind`'s doing applied, nothing else."""
    a, b = cur.split('\n'), tgt.split('\n')
    result = []

    def ok(x, y):   # differs, but only by this kind's tokens (a layout-only change is not one)
        return (WS.sub('', x) != WS.sub('', y) and kind.norm(x) == kind.norm(y) and kind.shows(x + y)
                and (kind.accept is None or kind.accept(x, y)))

    def only_tokens(lines):
        return lines and all(l.strip() and kind.norm(l) == '' and kind.shows(l) or
                             (kind is KIND_GUARD and l.strip() == '#endif') for l in lines)

    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        A, B = a[i1:i2], b[j1:j2]
        if tag == 'equal':
            result += A
            continue
        if ok('\n'.join(A), '\n'.join(B)) and (A and B or only_tokens(A or B)):
            result += B
            continue
        if tag in ('insert', 'delete'):
            if kind is KIND_GUARD and only_tokens(A or B) and (kind.accept is None):
                result += B
            else:
                result += A
            continue
        na, nb = [kind.norm(l) for l in A], [kind.norm(l) for l in B]
        for t2, k1, k2, l1, l2 in difflib.SequenceMatcher(None, na, nb, autojunk=False).get_opcodes():
            AA, BB = A[k1:k2], B[l1:l2]
            if t2 == 'equal':
                result += [y if ok(x, y) else x for x, y in zip(AA, BB)]
            elif t2 in ('insert', 'delete') and only_tokens(AA or BB) and kind.accept is None:
                result += BB
            else:
                result += AA
    return '\n'.join(result)


def apply_kind(work, target, kind, paths=None) -> list:
    changed = []
    for p in sorted(paths if paths is not None else work.files):
        cur, tgt = work.files.get(p), target.get(p)
        if cur is None or tgt is None or cur == tgt:
            continue
        cs, ts = cur.decode('utf-8', errors='surrogateescape'), tgt.decode('utf-8', errors='surrogateescape')
        if not (kind.shows(cs) or kind.shows(ts)):
            continue
        new = take_kind(cs, ts, kind)
        if new != cs:
            work.set(p, new.encode('utf-8', errors='surrogateescape'))
            changed.append(p)
    return changed



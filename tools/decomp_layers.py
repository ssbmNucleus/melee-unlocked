def author_env(squash):
    fields = out('log', '-1', '--format=%an%x00%ae%x00%aI', squash).split('\x00')
    name = out('config', 'user.name', check=False) or 'Netlee'
    email = out('config', 'user.email', check=False) or 'netlee@localhost'
    return {'GIT_AUTHOR_NAME': fields[0], 'GIT_AUTHOR_EMAIL': fields[1], 'GIT_AUTHOR_DATE': fields[2],
            'GIT_COMMITTER_NAME': name, 'GIT_COMMITTER_EMAIL': email}


def message(subject, body, layer, squash):
    text = subject + '\n\n' + body.strip() + '\n\nSplit out of "Version 1.0.5" (%s) by tools/decomp_layers.py.\n\n' % squash[:12]
    return text + '%s: %s\n' % (LAYER_TRAILER, layer) + CO_AUTHORS


def older_upstream_paths(base, squash, target, blobs):
    """Paths the squash took from an older upstream state than base: where it is nearer an earlier
    version of the file (in base's own history since the old pin) than base's version."""
    pin = ls_tree(OLD_PIN)
    up = ls_tree(base)
    versions = defaultdict(list)
    commit = None
    raw = out('log', '--reverse', '--raw', '--no-renames', '--no-abbrev', '--first-parent', '--format=@%H', OLD_PIN + '..' + base)
    for line in raw.splitlines():
        if line.startswith('@'):
            commit = line[1:]
        elif line.startswith(':'):
            meta, path = line.split('\t', 1)
            new = meta.split()[3]
            versions[path].append((commit, None if set(new) == {'0'} else new))

    def dist(x: bytes, y: bytes) -> int:
        a, b = x.split(b'\n'), y.split(b'\n')
        same = sum(m.size for m in difflib.SequenceMatcher(None, a, b, autojunk=False).get_matching_blocks())
        return len(a) + len(b) - 2 * same

    held = {}
    for path, (mode, sha) in target.items():
        p, u = pin.get(path), up.get(path)
        if u is not None and u[1] == sha or p == u:
            continue
        sdata = blobs.read(sha)
        du = dist(blobs.read(u[1]) if u else b'', sdata)
        best = None
        for c, b in [(OLD_PIN, p[1] if p else None)] + versions.get(path, [])[:-1]:
            d = dist(blobs.read(b) if b else b'', sdata)
            if best is None or d < best[0]:
                best = (d, c, b)
        if best and best[0] < du:
            held[path] = (best[1], best[2], best[0], du)
    return held


def build(args):
    base, squash, tip = rev(args.base), rev(args.squash), rev(args.tip)
    if not git_ok('merge-base', '--is-ancestor', OLD_PIN, base):
        raise Failure('%s does not descend from the old pin %s' % (base[:12], OLD_PIN[:12]))
    blobs = Blobs()
    target_tree = ls_tree(squash)
    target = {p: blobs.read(sha) for p, (mode, sha) in target_tree.items() if mode != '160000'}
    scratch = Path(args.keep) if args.keep else Path(tempfile.mkdtemp(prefix='decomp-layers-'))
    if scratch.exists():
        shutil.rmtree(scratch)
    scratch.mkdir(parents=True)
    work = Work(scratch / 'tree', blobs)
    work.dir.mkdir()
    work.load(base)
    env = author_env(squash)
    layers = []
    head = base

    def commit(subject, body, layer, kind_of):
        nonlocal head
        sha, n = work.commit(head, message(subject, body, layer, squash), env)
        if n == 0:
            print('  (no change: %s)' % subject)
            return
        head = sha
        layers.append({'commit': sha, 'subject': subject, 'files': n, 'layer': layer, 'kind': kind_of})
        print('%s %5d files  %s' % (sha[:12], n, subject), flush=True)

    # hold
    held = older_upstream_paths(base, squash, target_tree, blobs)
    for path, (c, b, d, du) in sorted(held.items()):
        work.set(path, blobs.read(b) if b else None)
    if held:
        commit('Hold %d paths at the upstream state the port was made from' % len(held),
               'Upstream %s changed these after the state the port took them from; the port\'s changes\n'
               'apply to the older text, so they are held there. Reverting this commit (and resolving\n'
               'against the layers above) is the catch-up still to do:\n\n%s'
               % (base[:12], '\n'.join('  %s  (as of upstream %s)' % (p, c[:12]) for p, (c, b, d, du) in sorted(held.items()))),
               'hold', 'hold')

    def rewriter(fn, kind, title, how):
        log = []
        touched, command = fn(work, target, log)
        changed = work.rescan(sorted(set(touched)))
        commit(title, how + '\n\nRegenerated: the rewriter\'s own output on the tree before this commit, nothing\n'
               'edited by hand.', kind.name, 'regenerated')
        return changed, command

    def by_hand(kind, title, body, paths=None):
        apply_kind(work, target, kind, paths)
        commit(title, body, kind.name, 'by hand')

    commands = {}
    _, commands['guard_asm'] = rewriter(run_guard_asm, KIND_GUARD, 'guard_asm: PowerPC assembly functions guarded with #ifndef MU_NATIVE',
                                        'python tools/guard_asm.py on the files the port guards.')
    by_hand(KIND_GUARD, 'By hand after guard_asm', 'Assembly guards the rewriter placed differently or not at all.')
    _, commands['gxpipe_rewrite'] = rewriter(run_gxpipe, KIND_GX, 'gxpipe_rewrite: GX write-gather pipe stores as GXW_ calls',
                                             'python tools/gxpipe_rewrite.py over the whole tree.')
    by_hand(KIND_GX, 'By hand after gxpipe_rewrite', 'Pipe writes the rewriter did not turn into calls, or turned differently.')
    _, commands['disc_convert'] = rewriter(run_disc_convert, KIND_CONVERT, 'disc_convert: structs that map disc data marked DISC_STRUCT, pointer fields as DISC_PTR slots',
                                           'python tools/disc_convert.py HEADER STRUCT... for every struct the port marks\n'
                                           '`} DISC_STRUCT` (the form the rewriter writes).')
    by_hand(KIND_CONVERT, 'By hand after disc_convert', 'Disc-layout markings the rewriter cannot make: structs marked in another position,\n'
            'anonymous structs, fields it lists for checking by hand, big-endian twins.')
    _, commands['disc_wrap'] = rewriter(run_disc_wrap, KIND_DP, 'disc_wrap: reads of disc pointer slots wrapped in DP()',
                                        'python tools/disc_wrap.py with every DISC_PTR field and slot array of the port, on\n'
                                        'the .c files that read slots.')
    by_hand(KIND_UNWRAP, 'disc_unwrap: DP() wraps of fields that are real pointers removed',
            'The DP() wraps the port does not have. tools/disc_unwrap.py removes them from the full\n'
            'native build\'s GCC errors, which this tree cannot give before the hand-written layers;\n'
            'they are taken from the ported tree instead (only removals of DP wraps).')
    by_hand(KIND_WRAP_MORE, 'By hand after disc_wrap', 'Slot reads the rewriter leaves alone (assigned, address taken, names it was not\n'
            'given) wrapped by hand: only additions of DP wraps.')
    by_hand(KIND_Z, 'cast_census --fix: integer-to-pointer casts zero-extended with MU_Z()',
            'tools/cast_census.py --fix wraps the sites GCC warns about in the full native build; this tree\n'
            'cannot give those warnings before the hand-written layers, so the wraps are taken from the\n'
            'ported tree (only MU_Z wraps).')
    _, commands['wrap_sqrt_args'] = rewriter(run_wrap_sqrt_args, KIND_P, 'wrap_sqrt_args: product terms of square-root arguments in MU_P()',
                                             'python tools/fma_exact/wrap_sqrt_args.py')
    _, commands['wrap_square_products'] = rewriter(run_wrap_square_products, KIND_P, 'wrap_square_products: squares of loaded values in MU_P()',
                                                   'python tools/fma_exact/wrap_square_products.py')
    by_hand(KIND_P, 'By hand after wrap_sqrt_args and wrap_square_products', 'MU_P wraps the two rewriters place differently, or not at all.')
    by_hand(KIND_TAG, 'tag_no_contract: functions the console never fused tagged MU_NO_CONTRACT',
            'tools/fma_exact/tag_no_contract.py reads the Static Recomp\'s translation of the retail code\n'
            'and a built game DLL, neither of which this tree has; the tags are taken from the ported tree.')
    by_hand(KIND_ANY, 'By hand: lines that need more than one kind of mechanical wrapper',
            'Lines whose only difference from the ported tree is mechanical, but of several kinds at once.')
    mech_tip = head

    # hand-written: port changes by the area of the file, then the changes recognized by what they name
    for key, title in AREAS:
        apply_hand(work, target, target_tree,
                   lambda p, text, key=key: area_of(p) == key and content_kind(p, text) is None,
                   lambda p, r, a, key=key: area_of(p) == key and content_kind(p, r + '\n' + a) is None)
        commit(title, 'Hand-written port changes in files of this area (by path), apart from the changes\n'
               'the layers after this one take by what they name.', 'hand:' + key, 'hand-written')
    for key, title, _ in CONTENT:
        apply_hand(work, target, target_tree,
                   lambda p, text, key=key: content_kind(p, text) == key,
                   lambda p, r, a, key=key: content_kind(p, r + '\n' + a) == key)
        commit(title, 'Hand-written changes, in any file, recognized by what they name (%s).' % key,
               'hand:' + key, 'hand-written')
    apply_hand(work, target, target_tree, lambda p, text: True, lambda p, r, a: True)
    commit('Port, the rest: changes the layers above split differently',
           'Differences left after the layers above, where a change was grouped differently once its\n'
           'neighbors had been applied.', 'hand:rest', 'hand-written')
    if out('rev-parse', head + '^{tree}') != out('rev-parse', squash + '^{tree}'):
        raise Failure('the layers do not end on the squash\'s tree')
    # the last layer stands for the squash: carry its import trailers for import-branch
    trailers = out('log', '-1', '--format=%(trailers:only)', squash)
    if trailers:
        msg = out('log', '-1', '--format=%B', head) + '\n' + trailers + '\n'
        fields = dict(env, GIT_COMMITTER_DATE=out('log', '-1', '--format=%cI', head))
        new = out('commit-tree', head + '^{tree}', '-p', out('rev-parse', head + '^'),
                  env=dict(os.environ, **fields), input=msg.encode())
        layers[-1]['commit'] = new
        head = new
    layer_tip = head
    print('layers end on %s (tree = squash %s)' % (layer_tip[:12], squash[:12]))
    if args.check:   # the same layers as an existing rebuilt branch: tree by tree
        old = out('rev-list', '--first-parent', '--reverse', find_layer_tip(args.check, squash), '^' + base).split()
        new = [l['commit'] for l in layers]
        same = len(old) == len(new) and all(out('rev-parse', a + '^{tree}') == out('rev-parse', b + '^{tree}')
                                            for a, b in zip(old, new))
        print('layers %s those of %s (%d and %d commits, compared tree by tree)'
              % ('equal' if same else 'DIFFER FROM', args.check, len(new), len(old)))
        if not same:
            raise Failure('the rebuilt layers differ from %s' % args.check)
    new_tip, mapping = replay_commits(tip, squash, layer_tip, base)
    report = {'base': base, 'squash': squash, 'tip': tip, 'held': {p: v[0] for p, v in held.items()},
              'layers': layers, 'mechanical_tip': mech_tip, 'layer_tip': layer_tip, 'new_tip': new_tip,
              'replayed': len(mapping), 'mapping': mapping, 'commands': commands}
    (scratch / 'report.json').write_text(json.dumps(report, indent=1), encoding='utf-8')
    print('report: %s' % (scratch / 'report.json'))
    if args.branch:
        create_branch(args.branch, new_tip)
    return 0


def replay_commits(tip, squash, layer_tip, base) -> tuple[str, dict]:
    """Every commit of tip made on the squash (or, like an imported side branch, on the old pin) again,
    with the same tree, message, authors and dates, its parents mapped onto layer_tip. Deterministic:
    the same commit replayed onto the same layers is the same new commit, so branches that share
    history keep sharing it. Upstream commits merged in are kept as they are."""
    tip = rev(tip)
    mapping = {squash: layer_tip, OLD_PIN: layer_tip}
    commits = out('rev-list', '--topo-order', '--reverse', tip, '^' + OLD_PIN, '^' + base, '--not', '--remotes=upstream').split()
    replayed = {}
    for c in commits:
        if c == squash:
            continue
        parents = out('rev-list', '--parents', '-n', '1', c).split()[1:]
        meta = out('log', '-1', '--format=%an%x00%ae%x00%aI%x00%cn%x00%ce%x00%cI', c).split('\x00')
        body = git('log', '-1', '--format=%B', c).decode('utf-8', errors='surrogateescape').rstrip('\n')
        body += '\n%s: %s\n' % (TRAILER, c) if re.search(r'(?m)^[\w-]+: .+\Z', body) else '\n\n%s: %s\n' % (TRAILER, c)
        cenv = dict(os.environ, GIT_AUTHOR_NAME=meta[0], GIT_AUTHOR_EMAIL=meta[1], GIT_AUTHOR_DATE=meta[2],
                    GIT_COMMITTER_NAME=meta[3], GIT_COMMITTER_EMAIL=meta[4], GIT_COMMITTER_DATE=meta[5])
        args_ = ['commit-tree', c + '^{tree}']
        for p in parents:
            args_ += ['-p', mapping.get(p, p)]   # a parent outside the range is an upstream commit
        mapping[c] = replayed[c] = out(*args_, env=cenv, input=body.encode('utf-8', errors='surrogateescape'))
    new_tip = mapping[tip]
    same = out('rev-parse', new_tip + '^{tree}') == out('rev-parse', tip + '^{tree}')
    print('replayed %d commits; new tip %s; tree %s the old tip\'s' % (len(replayed), new_tip[:12], 'equals' if same else 'DIFFERS FROM'))
    if not same:
        raise Failure('the rebuilt tip\'s tree differs from %s' % tip[:12])
    if any(git_ok('merge-base', '--is-ancestor', squash, p) for p in replayed.values()):
        raise Failure('the replayed history still reaches the squash %s' % squash[:12])
    return new_tip, replayed


def create_branch(name, sha):
    ref = 'refs/heads/' + name
    if git_ok('rev-parse', '--verify', '-q', ref):
        raise Failure('fork branch %s exists already; this command never moves a branch' % name)
    git('update-ref', ref, sha, '0' * 40)
    print('fork branch %s created at %s' % (name, sha[:12]))


def find_layer_tip(layers, squash) -> str:
    """The commit of a rebuilt branch that ends the layers: a layer commit with the squash's tree."""
    want = out('rev-parse', squash + '^{tree}')
    for line in out('log', '--first-parent', '--format=%H %T %(trailers:key=' + LAYER_TRAILER + ',valueonly)', layers).splitlines():
        fields = line.split()
        if len(fields) >= 3 and fields[1] == want:
            return fields[0]
    raise Failure('%s has no layer commit with the tree of %s' % (layers, squash[:12]))


def replay(args):
    squash = rev(args.squash)
    layer_tip = find_layer_tip(args.layers, squash)
    base = rev(args.base)
    print('layers end on %s' % layer_tip[:12])
    new_tip, _ = replay_commits(args.tip, squash, layer_tip, base)
    if args.branch:
        create_branch(args.branch, new_tip)
    return 0


def git_ok(*args) -> bool:
    return subprocess.run(['git', '-C', str(SUB), *args], capture_output=True).returncode == 0


def table(args):
    tip = rev(args.rev)
    rows = out('log', '--reverse', '--format=%H%x1f%s%x1f%(trailers:key=' + LAYER_TRAILER + ',valueonly)', '--first-parent',
               tip, '^' + DEFAULT_BASE).splitlines()
    for line in rows:
        sha, subject, layer = (line.split('\x1f') + ['', ''])[:3]
        if not layer.strip():
            continue
        n = len(out('diff-tree', '--no-commit-id', '--name-only', '-r', sha).splitlines())
        print('%s  %5d  %-24s %s' % (sha[:12], n, layer.strip(), subject))
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest='command', required=True)
    p = sub.add_parser('build', help='write the layered history (and, with --branch, a new fork branch at its tip)')
    p.add_argument('--base', default=DEFAULT_BASE, help='public decompilation commit to layer on (default 8e6529547)')
    p.add_argument('--squash', default=DEFAULT_SQUASH, help='the squash commit to split (default c5e898531)')
    p.add_argument('--tip', default='origin/netlee-next', help='the fork branch whose later commits are replayed')
    p.add_argument('--branch', help='create this fork branch at the new tip (refused if it exists)')
    p.add_argument('--keep', help='scratch folder to keep (the tree, report.json); default a temporary one')
    p.add_argument('--check', metavar='REBUILT', help='fail unless every layer has the tree of the same layer of '
                                                      'this rebuilt branch (e.g. netlee-rebased)')
    p.set_defaults(func=build)
    p = sub.add_parser('replay', help='move a fork branch made on the old squash onto the rebuilt layers')
    p.add_argument('tip', help='the fork branch or commit to replay (its history must hold the squash)')
    p.add_argument('--branch', help='create this fork branch at the replayed tip (refused if it exists)')
    p.add_argument('--layers', default='netlee-rebased', help='a rebuilt branch whose layers to replay onto')
    p.add_argument('--squash', default=DEFAULT_SQUASH)
    p.add_argument('--base', default=DEFAULT_BASE)
    p.set_defaults(func=replay)
    p = sub.add_parser('table', help='the layer commits of a rebuilt branch, with file counts')
    p.add_argument('rev', nargs='?', default='netlee-rebased')
    p.set_defaults(func=table)
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except Failure as error:
        print('decomp_layers: %s' % error, file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())

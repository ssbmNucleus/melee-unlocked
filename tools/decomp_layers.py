def content_kind(path, text):
    """The content layer a change belongs to (the last whose words it names), or None."""
    found = None
    for key, _, pattern in CONTENT:
        if key == 'safety':
            if ('/*' in text or '//' in text) and SAFETY_WORDS.search(text) and SAFETY_GUARD.search(text):
                found = key
        elif pattern.search(text):
            found = key
    if found is None and area_of(path) == 'pads':
        found = 'netplay'
    return found


TRIVIAL = {'', '{', '}', '};', '} else {', 'else', '#else', '#endif', 'break;', 'return;'}


def take_groups(cur: str, tgt: str, accept) -> str:
    """cur with the groups of differences from tgt that accept(removed, added) takes. Differences
    separated only by a few brace or blank lines form one group, so an inserted block that shares a
    closing brace with the old text is judged whole."""
    a, b = cur.split('\n'), tgt.split('\n')
    ops = difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes()
    groups, current = [], []
    for op in ops:
        tag, i1, i2, j1, j2 = op
        if tag == 'equal':
            small = i2 - i1 <= 3 and all(l.strip() in TRIVIAL for l in a[i1:i2])
            if current and small:
                current.append(op)
                continue
            if current:
                groups.append(current)
                current = []
            groups.append([op])
        else:
            current.append(op)
    if current:
        groups.append(current)
    result = []
    for group in groups:
        if len(group) == 1 and group[0][0] == 'equal':
            result += a[group[0][1]:group[0][2]]
            continue
        removed = '\n'.join(l for op in group if op[0] != 'equal' for l in a[op[1]:op[2]])
        added = '\n'.join(l for op in group if op[0] != 'equal' for l in b[op[3]:op[4]])
        take = accept(removed, added)
        for op in group:   # an equal op inside a group is the same on both sides
            result += b[op[3]:op[4]] if take else a[op[1]:op[2]]
    return '\n'.join(result)


def apply_hand(work, target, target_tree, accept_file, accept_change) -> list:
    """Bring files toward the ported tree: whole files (new, deleted, binary, mode) when
    accept_file(path, text) takes them, otherwise the groups accept_change(path, removed, added) takes."""
    changed = []
    for p in sorted(set(work.files) | set(target)):
        cur, tgt = work.files.get(p), target.get(p)
        mode = target_tree[p][0] if p in target_tree else None
        if cur == tgt and (tgt is None or work.modes.get(p) == mode):
            continue
        if cur is None or tgt is None or b'\0' in cur or b'\0' in tgt or cur == tgt:
            text = (cur or tgt).decode('utf-8', errors='surrogateescape')
            if accept_file(p, text):
                work.set(p, tgt)
                if tgt is not None:
                    work.modes[p] = mode
                changed.append(p)
            continue
        cs, ts = cur.decode('utf-8', errors='surrogateescape'), tgt.decode('utf-8', errors='surrogateescape')
        new = take_groups(cs, ts, lambda r, a, p=p: accept_change(p, r, a))
        if new != cs:
            work.set(p, new.encode('utf-8', errors='surrogateescape'))
            changed.append(p)
    return changed


def area_of(path: str) -> str:
    p = path.lower()
    parts = p.split('/')
    name = parts[-1]
    if p.startswith('libs/dolphin/'):
        if any(s in p for s in ('/gx/', '/mtx/', '/vi/', '/gd/')) or name.startswith(('gx', 'mtx', 'vi', 'gd')):
            return 'graphics'
        if any(s in p for s in ('/ax', '/ar/', '/ai/', '/dsp/', '/mix', '/sp/')):
            return 'audio'
        if '/card/' in p or name.startswith('card'):
            return 'card'
        if '/pad/' in p or '/si/' in p:
            return 'pads'
        return 'boot'
    if parts[0] == 'src' and len(parts) > 2 and parts[1] in ('msl', 'runtime', 'dolphin', 'metrotrk', 'trk', 'amcstubs', 'odenotstub'):
        return 'boot'
    if p.startswith('src/sysdolphin/baselib/'):
        if any(name.startswith(s) for s in ('axdriver', 'synth', 'sound', 'audio')):
            return 'audio'
        if name.startswith(('memory', 'initialize', 'debug', 'random', 'id.', 'list', 'archive', 'util', 'class', 'object', 'leak', 'perf')):
            return 'boot'
        if name.startswith(('controller', 'pad')):
            return 'pads'
        return 'graphics'
    if p.startswith('src/melee/'):
        area = parts[2] if len(parts) > 3 else ''
        if area == 'ft' or area == 'pl':
            return 'fighters'
        if area in ('it', 'ef'):
            return 'items'
        if area in ('gr', 'mp', 'cm'):
            return 'stages'
        if area in ('mn', 'ty', 'if', 'sc', 'vi', 'un', 'mm', 'gm'):
            return 'menus'
        if area == 'sfx':
            return 'audio'
        if area == 'lb':
            if any(s in name for s in ('audio', 'snd', 'music', 'bgm')):
                return 'audio'
            if any(s in name for s in ('card', 'memcard', 'snap', 'save')):
                return 'card'
            if any(s in name for s in ('pad', 'rumble')):
                return 'pads'
            if any(s in name for s in ('archive', 'dvd', 'file', 'heap', 'memory', 'arq', 'lbmthp', 'lbbgflash', 'lbrefract', 'lbshadow', 'lbcollision', 'lbvector', 'lbanim', 'lbtime', 'lbdebug', 'lblanguage', 'lb_00')):
                return 'boot' if any(s in name for s in ('archive', 'dvd', 'file', 'heap', 'memory', 'arq', 'debug', 'language')) else 'graphics'
            return 'graphics'
        if area == 'gm':
            return 'menus'
        if area == 'db':
            return 'boot'
        return 'other'
    return 'other'



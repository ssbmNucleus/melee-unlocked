class Failure(Exception):
    pass


# ---- git ----

def git(*args, env=None, input=None, check=True) -> bytes:
    r = subprocess.run(['git', '-C', str(SUB), *args], capture_output=True, env=env, input=input)
    if check and r.returncode:
        raise Failure('git %s failed: %s' % (' '.join(args[:3]), r.stderr.decode(errors='replace').strip()))
    return r.stdout


def out(*args, **kw) -> str:
    return git(*args, **kw).decode('utf-8', errors='replace').strip()


def rev(name) -> str:
    return out('rev-parse', '--verify', name + '^{commit}')


def ls_tree(treeish) -> dict:
    files = {}
    for line in git('ls-tree', '-r', '-z', treeish).split(b'\0'):
        if line:
            meta, path = line.split(b'\t', 1)
            mode, _, sha = meta.decode().split()
            files[path.decode('utf-8', errors='surrogateescape')] = (mode, sha)
    return files


class Blobs:
    def __init__(self):
        self.proc = subprocess.Popen(['git', '-C', str(SUB), 'cat-file', '--batch'],
                                     stdin=subprocess.PIPE, stdout=subprocess.PIPE)

    def read(self, sha) -> bytes:
        self.proc.stdin.write(sha.encode() + b'\n')
        self.proc.stdin.flush()
        head = self.proc.stdout.readline().split()
        if len(head) < 3:
            raise Failure('no object %s' % sha)
        data = self.proc.stdout.read(int(head[2]))
        self.proc.stdout.read(1)
        return data


# ---- the tree being built ----

class Work:
    """The tree being layered, kept in memory and mirrored to a scratch folder the rewriters run in."""

    def __init__(self, folder: Path, blobs: Blobs):
        self.dir = folder
        self.blobs = blobs
        self.files = {}      # path -> bytes
        self.modes = {}      # path -> mode
        self.committed = {}  # path -> (mode, sha) of the last commit

    def load(self, commit):
        self.committed = ls_tree(commit)
        for path, (mode, sha) in self.committed.items():
            if mode == '160000':
                continue
            data = self.blobs.read(sha)
            self.files[path], self.modes[path] = data, mode
            target = self.dir / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)

    def set(self, path, data: bytes | None, mode='100644'):
        target = self.dir / path
        if data is None:
            self.files.pop(path, None)
            self.modes.pop(path, None)
            if target.exists():
                target.unlink()
            return
        self.files[path] = data
        self.modes.setdefault(path, mode)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)

    def rescan(self, paths) -> list:
        """Take up what a rewriter wrote. Line ends are normalized as git's text=auto would on add."""
        changed = []
        for path in paths:
            target = self.dir / path
            data = target.read_bytes() if target.exists() else None
            old = self.files.get(path)
            if data is not None and b'\r\n' in data and (old is None or b'\r\n' not in old):
                data = data.replace(b'\r\n', b'\n')
                target.write_bytes(data)
            if data != old:
                changed.append(path)
                if data is None:
                    self.files.pop(path, None)
                else:
                    self.files[path] = data
                    self.modes.setdefault(path, '100644')
        return changed

    def commit(self, parent, message, author_env) -> tuple[str, int]:
        """A commit of the current tree on parent; returns (sha, files changed)."""
        changed = [p for p in set(self.files) | {p for p, (m, _) in self.committed.items() if m != '160000'}
                   if self.committed.get(p, (None, None))[1] is None or p not in self.files
                   or git_blob_sha(self.files[p]) != self.committed[p][1] or self.modes[p] != self.committed[p][0]]
        lines = []
        writes = [p for p in changed if p in self.files]
        if writes:
            listing = '\n'.join(str(self.dir / p) for p in writes) + '\n'
            shas = out('hash-object', '-w', '--no-filters', '--stdin-paths', input=listing.encode()).split()
            for p, sha in zip(writes, shas):
                lines.append('%s %s\t%s' % (self.modes[p], sha, p))
        for p in changed:
            if p not in self.files:
                lines.append('0 %s\t%s' % ('0' * 40, p))
        with tempfile.TemporaryDirectory(prefix='decomp-layers-') as scratch:
            env = dict(os.environ, GIT_INDEX_FILE=str(Path(scratch) / 'index'))
            git('read-tree', parent, env=env)
            if lines:
                git('update-index', '--index-info', env=env, input=('\n'.join(lines) + '\n').encode())
            tree = out('write-tree', env=env)
        sha = out('commit-tree', tree, '-p', parent, env=dict(os.environ, **author_env), input=message.encode())
        self.committed = ls_tree(sha)
        return sha, len(changed)


_BLOB_CACHE = {}


def git_blob_sha(data: bytes) -> str:
    key = id(data)
    hit = _BLOB_CACHE.get(key)
    if hit and hit[0] is data:
        return hit[1]
    sha = hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()
    _BLOB_CACHE[key] = (data, sha)
    return sha



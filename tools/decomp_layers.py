"""Rebuild the decomp fork's one-commit squash as reviewable layers on a newer public decompilation.

The fork's history used to be: the public pin 039c4bf4c, then "Version 1.0.5" (c5e898531), one
commit of about 1,583 files that mixes upstream progress copied in by hand, the output of the
porting rewriters in tools/, and hand-written port changes, then Netlee's real feature commits.
`build` writes the same final tree as a history that reads in layers:

    public decompilation at --base (upstream progress becomes upstream's own commits)
    hold:      paths the squash took from an older upstream state than --base, held there
    mechanical: one commit per porting rewriter, regenerated by running it on the tree before it,
               each followed (where the regenerated output is not what the port has) by a
               "by hand after <rewriter>" commit holding only changes of that rewriter's kind
    hand-written port changes, one commit per area (path based)
    the feature commits after the squash, re-parented onto that tip with their trees unchanged

Every layer commit is made in a temporary index; nothing in the submodule's working tree or its
existing branches is touched. The layer tip's tree must equal the squash's tree and the new tip's
tree the old tip's (checked; the command fails otherwise).

    python tools/decomp_layers.py build [--base REV] [--squash REV] [--tip REV] [--branch NAME] [--keep DIR] [--check REBUILT]
    python tools/decomp_layers.py replay TIP [--branch NAME] [--layers netlee-rebased]
        another fork branch made on the squash, moved onto the same layers (same tree per commit;
        history shared with an already replayed branch comes out as the same commits)
    python tools/decomp_layers.py table [REV]      the layer table of a rebuilt branch

docs/decomp-fork-history.md has the result and how to merge newer upstream progress.
"""

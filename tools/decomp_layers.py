DISC_CLOSE = re.compile(r'\}\s*DISC_STRUCT\b\s*(\**)\s*(\w*)')


def disc_struct_names(text):
    """The structs the ported file marks `} DISC_STRUCT` (the form disc_convert writes): their tag, or
    their typedef name."""
    names = []
    for m in DISC_CLOSE.finditer(text):
        depth, i = 0, m.start()
        while i >= 0:
            depth += {'}': 1, '{': -1}.get(text[i], 0)
            if depth == 0:
                break
            i -= 1
        head = text[max(0, i - 200):i]
        tag = re.search(r'struct\s+(\w+)\s*$', head)
        typedef = re.search(r'typedef\s+struct\s*\w*\s*$', head)
        if tag and tag.group(1) != 'DISC_STRUCT':
            names.append(tag.group(1))
        elif typedef and m.group(2) and not m.group(1):
            names.append(m.group(2))
    return names


def run_disc_convert(work, target, log):
    tool = load_tool('disc_convert.py')
    touched, commands = [], []
    for p in sorted(target):
        if p not in work.files or not p.endswith(('.h', '.c')) or b'DISC_STRUCT' not in target[p]:
            continue
        names = disc_struct_names(target[p].decode('utf-8', errors='replace'))
        if not names or not decodes(work.files[p]):
            continue
        argv = sys.argv
        sys.argv = ['disc_convert.py', str(work.dir / p), *names]
        try:
            from contextlib import redirect_stdout
            import io
            buf = io.StringIO()
            with redirect_stdout(buf):
                tool.main()
            log.extend('%s: %s' % (p, line) for line in buf.getvalue().splitlines() if line.strip())
        finally:
            sys.argv = argv
        touched.append(p)
        commands.append('python tools/disc_convert.py %s %s' % (p, ' '.join(names)))
    return touched, commands


def dp_names(text):
    """(fields, arrays) a ported file reads through DP(): the last member of each wrapped operand, or
    the global an element of which is wrapped."""
    fields, arrays = set(), set()
    for m in re.finditer(r'(?<!\w)DP\(', text):
        depth, k = 0, m.end() - 1
        while k < len(text):
            depth += {'(': 1, ')': -1}.get(text[k], 0)
            if depth == 0:
                break
            k += 1
        inner = text[m.end():k].strip()
        last = re.search(r'(?:->|\.)\s*(\w+)\s*$', inner)
        if last:
            fields.add(last.group(1))
            continue
        arr = re.match(r'(\w+)\s*\[', inner)
        if arr and not re.search(r'->|\.', inner.split('[', 1)[0]):
            arrays.add(arr.group(1))
    return fields, arrays


def run_disc_wrap(work, target, log):
    """tools/disc_wrap.py on each file the port reads slots in, given the field and array names that
    file reads through DP() in the port (the rewriter was run struct by struct, file by file)."""
    tool = load_tool('disc_wrap.py')
    files = sorted(p for p, d in target.items() if p.endswith(('.c', '.h')) and b'DP(' in d and p in work.files
                   and decodes(work.files[p]) and p.split('/')[0] in ('src', 'libs'))
    report, commands = [], []
    for p in files:
        fields, arrays = dp_names(target[p].decode('utf-8', errors='replace'))
        text = work.files[p].decode('utf-8')
        new = text
        if arrays:
            new = tool.wrap_arrays(new, sorted(arrays), report, p)
        if fields:
            new = tool.wrap(new, sorted(fields), report, p)
        if new != text:
            (work.dir / p).write_bytes(new.encode('utf-8'))
        commands.append('python tools/disc_wrap.py %s%s %s' % (''.join('--array %s ' % a for a in sorted(arrays)),
                                                              ' '.join('--field ' + f for f in sorted(fields)), p))
    log.append('%d files; %d sites left alone' % (len(files), len(report)))
    return files, commands


